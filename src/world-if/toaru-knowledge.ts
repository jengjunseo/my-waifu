export function selectRelevantCharacters(source: string, currentCast: string[], limit = 7): ToaruCharacterCard[] {
  const haystack = `${source}\n${currentCast.join(" ")}`.toLowerCase();
  const scored = TOARU_CHARACTERS.map((character) => {
    let score = currentCast.some((name) => name.includes(character.name) || character.aliases.some((alias) => name.includes(alias))) ? 5 : 0;
    for (const alias of [character.name, ...character.aliases]) {
      if (alias && haystack.includes(alias.toLowerCase())) score += 3;
    }
    return { character, score };
  }).sort((a, b) => b.score - a.score);

  const selected = scored.filter((item) => item.score > 0).slice(0, limit).map((item) => item.character);
  if (selected.length) return selected;

  return ["touma", "index", "mikoto", "kuroko", "shokuhou"]
    .map((id) => TOARU_CHARACTERS.find((character) => character.id === id))
    .filter((character): character is ToaruCharacterCard => Boolean(character));
}
